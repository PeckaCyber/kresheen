"""Every CWE and ATT&CK id a built-in rule cites must exist, and be current, in
MITRE's own data (pinned in tests/data/mitre_reference_ids.json, regenerated by
tests/data/refresh_mitre_reference_ids.py). A typo, a revoked technique or a
deprecated weakness would otherwise ship silently inside a rule."""

import json
import re
from pathlib import Path

import pytest

from kresheen.engine.threats.catalog import RULES
from kresheen.engine.threats.config_rules import CONFIG_RULES

_TABLE = json.loads((Path(__file__).parent.parent / "data" / "mitre_reference_ids.json").read_text())
_TECHNIQUES = _TABLE["attack"]["techniques"]
_ATLAS = _TABLE["atlas"]["techniques"]
_CWES = _TABLE["cwe"]["entries"]

_CITATIONS = [(rule.id, "attack", ref) for rule in (*RULES, *CONFIG_RULES) for ref in rule.attack] + [
    (rule.id, "cwe", ref) for rule in (*RULES, *CONFIG_RULES) for ref in rule.cwe
]


def test_reference_table_is_populated():
    assert len(_TECHNIQUES) > 500 and len(_CWES) > 800 and len(_ATLAS) > 100
    assert _TECHNIQUES["T1078"]["status"] == "active"
    assert _CWES["CWE-287"]["name"] == "Improper Authentication"


def test_rules_cite_something():
    assert len(_CITATIONS) > 100


@pytest.mark.parametrize(("rule_id", "kind", "ref"), sorted(set(_CITATIONS)))
def test_cited_reference_exists_and_is_current(rule_id: str, kind: str, ref: str):
    if kind == "attack" and ref.startswith("AML."):
        # `attack` refs may also carry MITRE ATLAS ids (AI-specific techniques).
        assert re.fullmatch(r"AML\.T\d{4}(\.\d{3})?", ref), f"{rule_id}: malformed ATLAS id {ref!r}"
        entry = _ATLAS.get(ref)
    elif kind == "attack":
        assert re.fullmatch(r"T\d{4}(\.\d{3})?", ref), f"{rule_id}: malformed ATT&CK id {ref!r}"
        entry = _TECHNIQUES.get(ref)
    else:
        assert re.fullmatch(r"CWE-\d+", ref), f"{rule_id}: malformed CWE id {ref!r}"
        entry = _CWES.get(ref)
    assert entry is not None, f"{rule_id} cites {ref}, which does not exist in the pinned MITRE data"
    assert entry["status"] == "active", f"{rule_id} cites {ref} ({entry['name']}), which is {entry['status']}"
